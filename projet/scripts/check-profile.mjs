import assert from 'node:assert/strict';
import worker from '../worker/index.js';
import { createTestDb } from './d1-test-db.mjs';
const { DB } = createTestDb();
const env={DB,NZOZI_ALLOWED_EMAILS:'a@example.test,b@example.test'};
const req=(id,method='GET',data=null,origin='https://test.example')=>new Request('https://test.example/api/profil',{method,headers:{'oai-authenticated-user-id':id,'oai-authenticated-user-email':id+'@example.test','Origin':origin,'Content-Type':'application/json'},...(data?{body:JSON.stringify(data)}:{})});
const profile={firstName:'Jean',lastName:'Test',contactEmail:'a@example.test',city:'Paris',region:'Île-de-France',languages:'Lingala',bio:'Ma présentation',rate:'255',community:'Ma communauté'};
assert.equal((await worker.fetch(req('a'),env)).status,200);
assert.equal((await worker.fetch(req('c'),env)).status,403);
assert.equal((await worker.fetch(req('a','PUT',profile,'https://evil.test'),env)).status,403);
assert.equal((await worker.fetch(req('a','PUT',{...profile,rate:'-1'}),env)).status,400);
const saved=await worker.fetch(req('a','PUT',profile),env);
assert.equal(saved.status,200);
assert.equal((await saved.json()).status,'pending');
const loaded=await (await worker.fetch(req('a'),env)).json();
assert.equal(loaded.profile.firstName,'Jean');
assert.equal(loaded.profile.community,'Ma communauté');
assert.equal(loaded.status,'pending');
assert.equal(loaded.published,false);
assert.equal((await worker.fetch(req('a','PUT',{...profile,community:''}),env)).status,200);
assert.equal((await (await worker.fetch(req('a'),env)).json()).profile.community,'');
assert.equal((await worker.fetch(req('a','PUT',{...profile,community:'x'.repeat(201)}),env)).status,400);
assert.equal((await (await worker.fetch(req('b'),env)).json()).profile,null);
assert.equal((await worker.fetch(req('a','PUT',{...profile,bio:'x'.repeat(2001)}),env)).status,400);
assert.equal((await worker.fetch(req('a'),{NZOZI_ALLOWED_EMAILS:env.NZOZI_ALLOWED_EMAILS})).status,503);
// Inscription ouverte : tout email vérifié peut créer un profil, qui reste en attente.
assert.equal((await worker.fetch(req('c','PUT',profile),{...env,NZOZI_OPEN_SIGNUP:'true'})).status,200);
assert.equal((await (await worker.fetch(req('c'),{...env,NZOZI_OPEN_SIGNUP:'true'})).json()).status,'pending');
assert.equal((await worker.fetch(req('c'),env)).status,403);
console.log('Sauvegarde, statut en attente, isolation par compte, validation, origine, inscription ouverte et erreurs : OK.');
